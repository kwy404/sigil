// Turns the brand icons in design/icons (and the mark in design/logo) into
// src/ui/glyph-data.ts, so the app draws them as vectors with any color.
// Run it after changing an icon: node scripts/build-glyphs.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sources = [
  ...readdirSync(join(root, 'design/icons'))
    .filter((file) => file.endsWith('.svg'))
    .sort()
    .map((file) => ({ name: file.slice(0, -4), path: join(root, 'design/icons', file) })),
  { name: 'sigil', path: join(root, 'design/logo/sigil-mark.svg') },
];

function attributes(tag) {
  const out = {};
  for (const match of tag.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
    out[match[1]] = match[2];
  }
  return out;
}

const num = (value) => Number(value);

function element(kind, attrs) {
  const secondary = attrs.class === 'gf-secondary' || attrs.opacity === '0.3';
  if (kind === 'path') {
    return { kind: 'path', d: attrs.d };
  }
  if (kind === 'circle') {
    return { kind: 'circle', cx: num(attrs.cx), cy: num(attrs.cy), r: num(attrs.r), ...(secondary ? { secondary: true } : {}) };
  }
  if (kind === 'rect') {
    return { kind: 'rect', x: num(attrs.x), y: num(attrs.y), width: num(attrs.width), height: num(attrs.height), rx: num(attrs.rx ?? 0) };
  }
  throw new Error(`Unsupported element <${kind}>`);
}

const lines = [];
for (const source of sources) {
  const svg = readFileSync(source.path, 'utf8');
  const elements = [];
  for (const match of svg.matchAll(/<(path|circle|rect)\b([^>]*)\/>/g)) {
    elements.push(element(match[1], attributes(match[2])));
  }
  lines.push(`  '${source.name}': ${JSON.stringify(elements)},`);
}

const output = `// Generated by scripts/build-glyphs.mjs from design/icons and design/logo/sigil-mark.svg. Do not edit.
import type { GlyphElement } from './glyph-types';

export const BRAND_GLYPHS = {
${lines.join('\n')}
} satisfies Record<string, readonly GlyphElement[]>;
`;

writeFileSync(join(root, 'src/ui/glyph-data.ts'), output);
console.log(`Wrote ${sources.length} glyphs`);
